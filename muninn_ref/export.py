"""Write a trained model for firmware: JSON (tools) and a C header (bare metal / Zephyr).

The C header matches nafarr's tsetlin driver: one array of 32-bit words per row for
tsetlin_write_clause(), and the booleanizer: thermometer thresholds, or the bigram
hash for text input. Optional class labels and a reject rule (an "unknown" class and a
minimum winning sum) go along.
"""

import json
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np

from muninn_ref import hardware
from muninn_ref.booleanize import Thermometer
from muninn_ref.text import MUL, Bigrams


def words(value, count):
    return [(value >> (32 * w)) & 0xFFFFFFFF for w in range(count)]


def _booleanizer(b):
    if isinstance(b, Bigrams):
        return {"type": "bigrams", "features": b.features}
    return {"type": "thermometer", "thresholds": b.thresholds.tolist(), "scale": b.scale}


def to_json(path, name, layout, rows, booleanizer=None, meta=None, labels=None, reject=None):
    """`reject`: {"class": index of the unknown class or None, "min_sum": n}; an input is
    rejected when the winner is that class or its sum is below n."""
    data = {"name": name,
            "layout": {"rows": layout.rows, "cols": layout.cols, "classes": layout.classes,
                       "tiles": layout.tiles, "rows_per_class": layout.rows_per_class},
            "rows": [f"{r:x}" for r in rows]}
    if booleanizer is not None:
        data["booleanizer"] = _booleanizer(booleanizer)
    if labels:
        data["labels"] = list(labels)
    if reject:
        data["reject"] = reject
    data["meta"] = meta or {}
    path.write_text(json.dumps(data, indent=1) + "\n")


BIGRAMS_C = f"""#ifndef MUNINN_BIGRAMS
#define MUNINN_BIGRAMS
/*
 * Hashed character bigrams of a command line (muninn_ref.text): lowercase, whitespace
 * runs as one space, '^' before and '$' after the line; each adjacent pair (a, b) sets
 * bit ({MUL} * a + b) % features of bits[] ((features + 31) / 32 words).
 */
static inline void muninn_bigram_set(unsigned int *bits, unsigned int features,
\t\t\t\t     unsigned int a, unsigned int b)
{{
\tunsigned int h = ({MUL} * a + b) % features;

\tbits[h / 32] |= 1u << (h % 32);
}}

static inline void muninn_bigrams(const char *line, unsigned int features,
\t\t\t\t  unsigned int *bits)
{{
\tunsigned int prev = '^', space = 0, c, i;

\tfor (i = 0; i < (features + 31) / 32; i++)
\t\tbits[i] = 0;
\tfor (; *line; line++) {{
\t\tc = (unsigned char)*line;
\t\tif (c == ' ' || c == '\\t' || c == '\\r' || c == '\\n') {{
\t\t\tspace = prev != '^';
\t\t\tcontinue;
\t\t}}
\t\tif (c >= 0x80)
\t\t\tc = '?';
\t\tif (c >= 'A' && c <= 'Z')
\t\t\tc += 'a' - 'A';
\t\tif (space) {{
\t\t\tmuninn_bigram_set(bits, features, prev, ' ');
\t\t\tprev = ' ';
\t\t\tspace = 0;
\t\t}}
\t\tmuninn_bigram_set(bits, features, prev, c);
\t\tprev = c;
\t}}
\tmuninn_bigram_set(bits, features, prev, '$');
}}
#endif"""


def to_header(path, name, layout, rows, booleanizer=None, labels=None, reject=None):
    n = (layout.literals + 31) // 32
    guard = f"MUNINN_MODEL_{name.upper()}_H"
    out = ["/*", " * SPDX-FileCopyrightText: 2026 aesc silicon", " *",
           " * SPDX-License-Identifier: Apache-2.0", " *",
           f" * Generated by muninn_ref: Tsetlin model '{name}'.", " */", "",
           f"#ifndef {guard}", f"#define {guard}", "",
           f"#define {name.upper()}_ROWS\t\t{layout.rows}",
           f"#define {name.upper()}_LITERALS\t{layout.literals}",
           f"#define {name.upper()}_WORDS\t\t{n}",
           f"#define {name.upper()}_CLASSES\t\t{layout.classes}",
           f"#define {name.upper()}_ROWS_PER_CLASS\t{layout.rows_per_class}", "",
           f"static const unsigned int {name}_include[{layout.rows}][{n}] = {{"]
    for r in rows:
        out.append("\t{ " + ", ".join(f"0x{w:08x}" for w in words(r, n)) + " },")
    out.append("};")
    N = name.upper()
    if labels:
        out += ["", f"static const char *const {name}_labels[{len(labels)}] = {{"]
        out += [f'\t"{lbl}",' for lbl in labels] + ["};"]
    if reject:
        out += ["", "/* reject: winner is the unknown class, or its sum is below MIN_SUM */"]
        if reject.get("class") is not None:
            out.append(f"#define {N}_UNKNOWN\t\t{reject['class']}")
        out.append(f"#define {N}_MIN_SUM\t\t{reject.get('min_sum', 0)}")
    if isinstance(booleanizer, Bigrams):
        out += ["", f"#define {N}_FEATURES\t{booleanizer.features}", "", BIGRAMS_C]
    elif booleanizer is not None:
        if not booleanizer.scale:
            raise ValueError("firmware needs a quantized booleanizer (scale)")
        t = booleanizer.thresholds
        f, b = t.shape
        out += ["", f"/* bit k of feature f is 1 when round(value * {booleanizer.scale}) > "
                f"thresholds[f][k] */",
                f"#define {name.upper()}_FEATURES\t{f}", f"#define {name.upper()}_BITS\t\t{b}",
                f"#define {name.upper()}_SCALE\t\t{booleanizer.scale}",
                f"static const int {name}_thresholds[{f}][{b}] = {{"]
        for row in t:
            out.append("\t{ " + ", ".join(str(int(v)) for v in row) + " },")
        out.append("};")
    out += ["", "#endif", ""]
    path.write_text("\n".join(out))


@dataclass
class Model:
    """An exported model: clause-array contents plus the booleanizer that feeds it."""
    name: str
    layout: hardware.Layout
    rows: list
    booleanizer: object = None
    meta: dict = field(default_factory=dict)
    labels: list = None
    reject: dict = None

    @property
    def text(self):
        return isinstance(self.booleanizer, Bigrams)

    def features(self, X):
        """Raw inputs (value vectors, or lines of text) -> boolean features."""
        if self.text:
            return self.booleanizer.transform(list(X))
        X = np.atleast_2d(np.asarray(X))
        return self.booleanizer.transform(X) if self.booleanizer else X.astype(bool)

    def classify(self, x):
        """Class sums and winner for one raw input."""
        lit = hardware.literals(self.features([x])[0], self.layout)
        return hardware.classify(self.rows, lit, self.layout)

    def decide(self, x):
        """(class or None when rejected, sums) for one raw input."""
        sums, winner = self.classify(x)
        if self.reject and (winner == self.reject.get("class")
                            or sums[winner] < self.reject.get("min_sum", -len(self.rows))):
            return None, sums
        return winner, sums

    def label(self, k):
        return self.labels[k] if self.labels and k is not None else k

    def predict(self, X):
        return hardware.predict(self.rows, self.features(X), self.layout)


def load(path):
    """Read a model written by to_json()."""
    data = json.loads(Path(path).read_text())
    lay = data["layout"]
    layout = hardware.Layout(rows=lay["rows"], cols=lay["cols"], classes=lay["classes"],
                             group=lay["rows_per_class"], tiles=lay.get("tiles", 1))
    rows = [int(r, 16) for r in data["rows"]]
    if len(rows) != layout.rows:
        raise ValueError(f"{path}: {len(rows)} rows, layout has {layout.rows}")
    if any(r >> layout.literals for r in rows):
        raise ValueError(f"{path}: include bits beyond {layout.literals} literal columns")
    b = data.get("booleanizer")
    if b is None and "thresholds" in data:                 # first format: top level
        b = {"type": "thermometer", "thresholds": data["thresholds"], "scale": data.get("scale")}
    booleanizer = None
    if b and b["type"] == "bigrams":
        booleanizer = Bigrams(b["features"])
    elif b and b["type"] == "thermometer":
        t = np.array(b["thresholds"])
        booleanizer = Thermometer(t.shape[1], scale=b.get("scale"))
        booleanizer.thresholds = t
    elif b:
        raise ValueError(f"{path}: unknown booleanizer '{b['type']}'")
    return Model(data["name"], layout, rows, booleanizer, data.get("meta", {}),
                 data.get("labels"), data.get("reject"))
